const GENISLIK = 5, BOSLUK = 1.9;

// Metni ölçer: '_' sonraki karakteri alt indis, '^' üst indis yapar.
function coz(metin) {
  const out = [];
  for (let i = 0; i < metin.length; i++) {
    const c = metin[i];
    if ((c === '_' || c === '^') && i + 1 < metin.length) {
      out.push({ ch: metin[++i].toUpperCase(), kucuk: true, ust: c === '^' });
    } else {
      out.push({ ch: c.toUpperCase(), kucuk: false, ust: false });
    }
  }
  return out;
}

export function yaziGenisligi(metin, boy = 7) {
  const k = boy / 7;
  let w = 0;
  for (const g of coz(metin)) w += (GENISLIK * (g.kucuk ? 0.6 : 1) + BOSLUK) * k;
  return w - BOSLUK * k;
}

// Çizgiyi yuvarlak uçlu şeride çevirir.
function serit(a, b, kal) {
  const dx = b[0] - a[0], dy = b[1] - a[1];
  const l = Math.hypot(dx, dy);
  const r = kal / 2;
  if (l < 1e-6) return yay(a[0], a[1], r, r, 0, 360, 10);
  const nx = -dy / l * r, ny = dx / l * r;
  const a0 = Math.atan2(dy, dx) * 180 / Math.PI;
  return [
    [a[0] + nx, a[1] + ny], [b[0] + nx, b[1] + ny],
    ...yay(b[0], b[1], r, r, a0 + 90, a0 - 90, 7),
    [a[0] - nx, a[1] - ny],
    ...yay(a[0], a[1], r, r, a0 - 90, a0 - 270, 7),
  ];
}

/**
 * Kabartma yazı üretir. Sol alt köşe (0,0), taban z=z0.
 * @param {string} metin  '_' alt indis, '^' üst indis (örn. 'CO_2', 'NADP^+')
 * @param {object} o  { boy: harf yüksekliği, kal: çizgi kalınlığı, h: kabartma yüksekliği, z0 }
 */
export function yazi(metin, o = {}) {
  const boy = o.boy ?? 7, kal = o.kal ?? 1.1, h = o.h ?? 0.8, z0 = o.z0 ?? 0;
  const k = boy / 7;
  const m = new Mesh();
  let x = 0;
  for (const g of coz(metin)) {
    const s = k * (g.kucuk ? 0.6 : 1);
    const dy = g.kucuk ? (g.ust ? boy * 0.42 : -boy * 0.06) : 0;
    for (const cizgi of FONT[g.ch] || []) {
      for (let i = 0; i < cizgi.length - 1; i++) {
        const a = [x + cizgi[i][0] * s, dy + cizgi[i][1] * s];
        const b = [x + cizgi[i + 1][0] * s, dy + cizgi[i + 1][1] * s];
        m.add(extrude(serit(a, b, kal), z0, z0 + h));
      }
    }
    x += (GENISLIK * (g.kucuk ? 0.6 : 1) + BOSLUK) * k;
  }
  return m;
}

// Ortalanmış yazı: (cx, cy) merkez olacak şekilde.
export function yaziOrtala(metin, cx, cy, o = {}) {
  const boy = o.boy ?? 7;
  return yazi(metin, o).translate(cx - yaziGenisligi(metin, boy) / 2, cy - boy / 2, 0);
}
