import { Mesh, extrude } from './mesh.js';

const yay = (cx, cy, rx, ry, a0, a1, n = 14) => {
  const p = [];
  for (let i = 0; i <= n; i++) {
    const a = (a0 + (a1 - a0) * i / n) * Math.PI / 180;
    p.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return p;
};
const halka = (cx, cy, rx, ry) => yay(cx, cy, rx, ry, 0, 360, 22);

